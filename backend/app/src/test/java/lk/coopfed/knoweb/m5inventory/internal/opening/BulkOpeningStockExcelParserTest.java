package lk.coopfed.knoweb.m5inventory.internal.opening;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.Base64;
import java.util.List;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;
import lk.coopfed.knoweb.kernel.api.ProblemException;
import lk.coopfed.knoweb.m5inventory.api.LotCondition;
import lk.coopfed.knoweb.m5inventory.api.OpeningStockRow;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

class BulkOpeningStockExcelParserTest {

    @Test
    @DisplayName("Parses standard Excel template bytes generated by OpeningStockTemplateGenerator")
    void parsesGeneratedTemplateBytes() {
        byte[] xlsxBytes = OpeningStockTemplateGenerator.generateTemplateBytes();
        assertThat(xlsxBytes).isNotEmpty();

        List<OpeningStockRow> rows = BulkOpeningStockExcelParser.parse(xlsxBytes);
        assertThat(rows).hasSize(4);

        OpeningStockRow r1 = rows.get(0);
        assertThat(r1.sku()).isEqualTo("DHAL1");
        assertThat(r1.uom()).isEqualTo("KG");
        assertThat(r1.qty()).isEqualByComparingTo("150.000");
        assertThat(r1.unitCost()).isEqualByComparingTo("310.5000");
        assertThat(r1.batchNo()).isEqualTo("D1");
        assertThat(r1.expiryDate()).isNotNull();
        assertThat(r1.printedMrp()).isEqualByComparingTo("360.00");
        assertThat(r1.condition()).isEqualTo(LotCondition.GOOD);

        OpeningStockRow r2 = rows.get(1);
        assertThat(r2.sku()).isEqualTo("RICE-SAMBA-5KG");
        assertThat(r2.uom()).isEqualTo("NOS");
        assertThat(r2.qty()).isEqualByComparingTo("40.000");
        assertThat(r2.unitCost()).isEqualByComparingTo("1150.0000");
        assertThat(r2.condition()).isEqualTo(LotCondition.GOOD);

        OpeningStockRow r3 = rows.get(2);
        assertThat(r3.sku()).isEqualTo("MILK-POWDER-400G");
        assertThat(r3.uom()).isEqualTo("PKT");
        assertThat(r3.qty()).isEqualByComparingTo("25.000");
        assertThat(r3.unitCost()).isEqualByComparingTo("980.0000");

        OpeningStockRow r4 = rows.get(3);
        assertThat(r4.sku()).isEqualTo("DHAL1");
        assertThat(r4.uom()).isEqualTo("KG");
        assertThat(r4.qty()).isEqualByComparingTo("2.000");
        assertThat(r4.unitCost()).isEqualByComparingTo("310.5000");
        assertThat(r4.condition()).isEqualTo(LotCondition.DAMAGED);
    }

    @Test
    @DisplayName("Parses base64-encoded xlsx template")
    void parsesBase64String() {
        byte[] xlsxBytes = OpeningStockTemplateGenerator.generateTemplateBytes();
        String b64 = Base64.getEncoder().encodeToString(xlsxBytes);

        List<OpeningStockRow> rows = BulkOpeningStockExcelParser.parse(b64);
        assertThat(rows).hasSize(4);
        assertThat(rows.get(0).sku()).isEqualTo("DHAL1");
    }

    @Test
    @DisplayName("Falls back to CSV parsing when plain text CSV is supplied")
    void fallsBackToCsvWhenTextSupplied() {
        String csv =
                """
                SKU,UOM,Quantity,Unit Cost,Batch No,Expiry Date,MRP,Condition
                DHAL1,KG,50,180.50,B101,2027-12-31,220,GOOD
                """;

        List<OpeningStockRow> rows = BulkOpeningStockExcelParser.parse(csv);
        assertThat(rows).hasSize(1);
        assertThat(rows.get(0).sku()).isEqualTo("DHAL1");
        assertThat(rows.get(0).uom()).isEqualTo("KG");
        assertThat(rows.get(0).qty()).isEqualByComparingTo("50");
    }

    @Test
    @DisplayName("Returns empty list on null or empty input")
    void emptyOrNullReturnsEmpty() {
        assertThat(BulkOpeningStockExcelParser.parse((byte[]) null)).isEmpty();
        assertThat(BulkOpeningStockExcelParser.parse(new byte[0])).isEmpty();
        assertThat(BulkOpeningStockExcelParser.parse((String) null)).isEmpty();
        assertThat(BulkOpeningStockExcelParser.parse("")).isEmpty();
        assertThat(BulkOpeningStockExcelParser.parse("   \n ")).isEmpty();
    }

    @Test
    @DisplayName("Rejects zip bomb that exceeds max entry count")
    void rejectsZipWithTooManyEntries() throws IOException {
        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        try (ZipOutputStream zos = new ZipOutputStream(baos)) {
            for (int i = 0; i < 60; i++) {
                zos.putNextEntry(new ZipEntry("file" + i + ".txt"));
                zos.write("data".getBytes(StandardCharsets.UTF_8));
                zos.closeEntry();
            }
        }

        assertThatThrownBy(() -> BulkOpeningStockExcelParser.parse(baos.toByteArray()))
                .isInstanceOf(ProblemException.class)
                .hasMessage("m5.opening.excel_parse_error");
    }

    @Test
    @DisplayName("Rejects malformed zip data")
    void rejectsMalformedZip() {
        byte[] corrupted = new byte[] {0x50, 0x4b, 0x03, 0x04, 0x00, 0x00, 0x12, 0x34};
        assertThatThrownBy(() -> BulkOpeningStockExcelParser.parse(corrupted))
                .isInstanceOf(ProblemException.class)
                .hasMessage("m5.opening.excel_parse_error");
    }
}
