package lk.coopfed.knoweb.till.core.shop

import kotlinx.datetime.LocalDate
import kotlinx.serialization.Serializable
import lk.coopfed.knoweb.till.core.model.OutboxEntry
import lk.coopfed.knoweb.till.core.money.Money
import lk.coopfed.knoweb.till.core.money.Qty

/**
 * Line of an offline shop document (GRN, stock count, write-off, repack, transfer).
 */
@Serializable
data class ShopDocumentLine(
    val lineNo: Int,
    val lineId: String,
    val skuId: String,
    val batchId: String? = null,
    val batchNo: String? = null,
    val uomCode: String,
    val qty: Qty,
    val unitPrice: Money = Money.ZERO,
    val lineTotal: Money = Money.ZERO,
    val unitCostAtIssue: Money? = null,
    val lossCategory: String? = null,
    val referenceLineId: String? = null,
    val receivedQty: Qty? = null,
    val damagedQty: Qty? = null,
    val expectedQty: Qty? = null,
    val countedQty: Qty? = null,
    val condition: String? = null,
    val skipped: Boolean = false,
    val skipReason: String? = null,
)

/**
 * Shared document header for offline shop operations (doc 18, doc 24A, doc 25A).
 */
@Serializable
data class ShopDocumentHeader(
    val documentId: String,
    val docTypeCode: String,
    val seriesId: String,
    val docNumber: Long,
    val docNumberDisplay: String,
    val ownerEntityId: String,
    val counterpartyEntityId: String? = null,
    val locationId: String,
    val tillPositionId: String,
    val deviceId: String,
    val status: String,
    val issuedAt: Long,
    val issuedLocal: String,
    val businessDate: LocalDate,
    val operatorUserId: String,
    val currency: String = "LKR",
    val netAmount: Money = Money.ZERO,
    val taxAmount: Money = Money.ZERO,
    val grossAmount: Money = Money.ZERO,
    val referenceDocumentId: String? = null,
    val origin: String = "OFFLINE",
    val deviceSeq: Long,
)

/**
 * Document attachment reference (e.g., photo of damaged goods for GRN or write-off).
 */
@Serializable
data class ShopAttachmentReference(
    val attachmentId: String,
    val objectKey: String,
    val contentHash: String,
)

/**
 * Immutable state history row for document lifecycle transitions.
 */
@Serializable
data class ShopStateHistory(
    val historyId: String,
    val documentId: String,
    val fromStatus: String? = null,
    val toStatus: String,
    val occurredAt: Long,
    val occurredLocal: String,
    val actorUserId: String,
    val reasonCode: String? = null,
    val reasonText: String? = null,
)

/**
 * Stock movement record generated by stock-affecting operations.
 */
@Serializable
data class ShopStockMovement(
    val movementId: String,
    val movementSeq: Long? = null,
    val locationId: String,
    val skuId: String? = null,
    val batchId: String? = null,
    val lotId: String? = null,
    val condition: String = "GOOD",
    val qtyDelta: String,
    val movementType: String,
    val unitCostAtMovement: Money? = null,
    val documentId: String? = null,
    val documentLineId: String? = null,
    val occurredAt: Long,
    val occurredLocal: String,
    val operatorUserId: String,
    val deviceId: String? = null,
)

/**
 * Audit event row recorded alongside shop operations.
 */
@Serializable
data class ShopAuditEvent(
    val auditId: String,
    val eventTypeCode: String,
    val occurredAt: Long,
    val occurredLocal: String,
    val ownerEntityId: String? = null,
    val locationId: String? = null,
    val actorUserId: String,
    val deviceId: String? = null,
    val tillPositionId: String? = null,
    val subjectTable: String? = null,
    val subjectId: String? = null,
    val documentId: String? = null,
    val beforeState: String? = null,
    val afterState: String? = null,
    val reasonCode: String? = null,
    val reasonText: String? = null,
    val deviceSeq: Long? = null,
    val correlationId: String? = null,
)

/**
 * Complete sealed shop-operation bundle ready for local persistence and offline outbox sync.
 */
data class ShopOperationBundle(
    val document: ShopDocumentHeader,
    val lines: List<ShopDocumentLine>,
    val eventType: String,
    val contentHash: String,
    val outboxEntry: OutboxEntry,
    val stateHistory: List<ShopStateHistory>,
    val stockMovements: List<ShopStockMovement> = emptyList(),
    val auditEvents: List<ShopAuditEvent> = emptyList(),
    val attachments: List<ShopAttachmentReference> = emptyList(),
)

// ---- Input Specifications ----

data class GrnLineInput(
    val skuId: String,
    val batchId: String? = null,
    val batchNo: String? = null,
    val uomCode: String,
    val receivedQty: Qty,
    val damagedQty: Qty = Qty.ZERO,
    val expectedQty: Qty? = null,
    val unitCost: Money = Money.ZERO,
)

data class GrnOperationInput(
    val lines: List<GrnLineInput>,
    val supplierId: String? = null,
    val dropId: String? = null,
    val deliveryDocumentId: String? = null,
    val attachments: List<ShopAttachmentReference> = emptyList(),
    val countedBy: String? = null,
    val confirmedBy: String? = null,
)

data class StockCountLineInput(
    val skuId: String,
    val batchId: String? = null,
    val uomCode: String,
    val countedQty: Qty,
    val expectedQty: Qty? = null,
    val condition: String = "GOOD",
    val skipped: Boolean = false,
    val skipReason: String? = null,
)

data class StockCountOperationInput(
    val lines: List<StockCountLineInput>,
    val taskId: String? = null,
    val snapshotVersion: Long? = null,
)

data class WriteOffLineInput(
    val skuId: String,
    val batchId: String? = null,
    val uomCode: String,
    val qty: Qty,
    val unitCost: Money = Money.ZERO,
    val lossCategory: String? = null,
)

data class WriteOffOperationInput(
    val lines: List<WriteOffLineInput>,
    val category: String,
    val reason: String,
    val witnessUserId: String? = null,
    val attachments: List<ShopAttachmentReference> = emptyList(),
)

data class ConsumedLotInput(
    val lotId: String,
    val skuId: String,
    val batchId: String? = null,
    val consumedQty: Qty,
    val unitCost: Money = Money.ZERO,
)

data class RepackOperationInput(
    val recipeId: String,
    val inputLotIds: List<String>,
    val outputSkuId: String,
    val outputUom: String,
    val actualOutputQty: Qty,
    val outputBatchId: String? = null,
    val consumedLots: List<ConsumedLotInput> = emptyList(),
)

data class TransferLineInput(
    val skuId: String,
    val batchId: String? = null,
    val uomCode: String,
    val qty: Qty,
    val unitCost: Money = Money.ZERO,
)

data class StockTransferOperationInput(
    val lines: List<TransferLineInput>,
    val destinationLocationId: String,
    val transferRequestId: String? = null,
    val vehicleNo: String? = null,
)
